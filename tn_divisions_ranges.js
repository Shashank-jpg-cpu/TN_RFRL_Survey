// Standardized 51 DFO Credentials Directory (Division & Username mixed with fixed passwords)
window.TN_DFO_CREDENTIALS = {};

(function initDfoCredentials() {
    const divs = Object.keys(window.TN_FOREST_HIERARCHY);
    const seen = new Set();

    divs.forEach(div => {
        let clean = div.toLowerCase().replace(/division|forest|territory/gi, '').replace(/[^a-z0-9]/gi, '');
        if (!clean) clean = div.toLowerCase().replace(/[^a-z0-9]/gi, '');
        
        let username = `dfo_${clean}`;
        let password = `${clean}@dfo123`;

        if (seen.has(username)) {
            clean = div.toLowerCase().replace(/[^a-z0-9]/gi, '');
            username = `dfo_${clean}`;
            password = `${clean}@dfo123`;
        }
        seen.add(username);

        window.TN_DFO_CREDENTIALS[div] = {
            division: div,
            username: username,
            password: password
        };
    });
})();

window.getDfoCreds = function(divisionName) {
    return window.TN_DFO_CREDENTIALS[divisionName] || {
        division: divisionName,
        username: `dfo_${divisionName.toLowerCase().replace(/[^a-z0-9]/gi, '')}`,
        password: `dfo@123`
    };
};
